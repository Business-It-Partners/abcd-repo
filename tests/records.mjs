import { fixtureArgs as profileArgs } from './profile.mjs';
import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: [root, ...profileArgs], env });
const page = await app.firstWindow();
const errors = []; page.on('pageerror', e => errors.push(e.message));
const checks = [];
const check = (name, value) => { assert.ok(value, name); checks.push(name); console.log('PASS', name); };
const phase = value => page.waitForFunction(p => document.querySelector('[data-testid="records-window"]').dataset.phase === p, value);
try {
  await page.getByRole('button', { name: 'Records', exact: true }).click(); await phase('visible');
  const table = page.getByRole('table', { name: 'Records', exact: true });
  check('Records launches from its dock icon with six column headings and six demo records', await table.locator('thead th').count() === 6 && await table.locator('tbody tr').count() === 6);
  const colors = await table.locator('tbody tr').evaluateAll(rows => rows.slice(0, 2).map(row => getComputedStyle(row).backgroundColor));
  check('Table rows have alternating colors', colors[0] !== colors[1]);
  await page.mouse.move(20, 80); await page.screenshot({ path: path.join(root, 'artifacts/records-table.png') });
  await page.getByRole('button', { name: 'Add record', exact: true }).click();
  const form = page.getByRole('dialog', { name: 'Add record', exact: true });
  check('Add opens a focused accessible form', await form.isVisible() && await form.getByLabel('Item name', { exact: true }).evaluate(e => e === document.activeElement));
  const scope = await page.getByTestId('records-window').boundingBox();
  const overlay = await page.getByTestId('records-window').locator('.record-modal-layer').boundingBox();
  const title = await page.getByTestId('records-window').locator('.studio-title').boundingBox();
  check('Modal stays in app content and leaves its title frame clear',
    overlay.x >= scope.x && overlay.y >= title.y + title.height &&
    overlay.x + overlay.width <= scope.x + scope.width && overlay.y + overlay.height <= scope.y + scope.height);
  await page.getByRole('button', { name: 'Motion Studio', exact: true }).click();
  check('Other dock apps remain usable while Records form is open', await page.getByTestId('studio-window').isVisible() && await form.isVisible());
  await page.getByRole('button', { name: 'Records', exact: true }).click();
  await form.getByRole('button', { name: 'Save record' }).click();
  check('Empty submission is blocked', await form.isVisible() && await table.locator('tbody tr').count() === 6);
  await form.getByLabel('Item name', { exact: true }).fill('Ergonomic chair');
  await form.getByLabel('Category', { exact: true }).selectOption('Equipment');
  await form.getByLabel('Quantity', { exact: true }).fill('7');
  await form.getByLabel('Unit price', { exact: true }).fill('125.50');
  await page.screenshot({ path: path.join(root, 'artifacts/records-form.png') });
  await form.getByRole('button', { name: 'Save record' }).click();
  check('Save inserts the entered values into the table', await table.locator('tbody tr').count() === 7 && (await table.locator('tbody tr').last().innerText()).includes('125.50'));
  await page.getByRole('button', { name: 'Add record', exact: true }).click();
  await form.getByLabel('Item name', { exact: true }).fill('Unsaved record');
  await form.getByRole('button', { name: 'Cancel', exact: true }).click();
  check('Cancel does not insert a record', await table.locator('tbody tr').count() === 7 && !await form.isVisible());
  await page.getByRole('button', { name: 'Minimize Records', exact: true }).click(); await phase('minimized');
  check('Records minimizes with a captured dock preview', await page.getByAltText('Records snapshot').count() === 1);
  await page.getByRole('button', { name: 'Restore Records', exact: true }).click(); await phase('visible');
  check('Genie restore preserves the added record', await table.getByRole('rowheader', { name: 'Ergonomic chair', exact: true }).count() === 1);
  await page.getByRole('button', { name: 'Motion Studio', exact: true }).click();
  check('Records and Motion Studio can both stay open', await page.getByTestId('studio-window').isVisible() && await page.getByTestId('records-window').isVisible());
  await page.getByRole('button', { name: 'Records', exact: true }).click();
  const before = await page.getByTestId('records-window').boundingBox();
  await page.getByRole('button', { name: 'Maximize Records', exact: true }).click();
  check('Records maximize remains internal', (await page.getByTestId('records-window').boundingBox()).width > before.width && await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isFullScreen()));
  const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }));
  await page.mouse.move(viewport.width / 2, viewport.height / 2);
  await page.waitForFunction(() => document.querySelector('main').classList.contains('is-immersive'));
  const expanded = await page.getByTestId('records-window').boundingBox();
  const chromeBounds=await page.evaluate(()=>({bar:document.querySelector('.desktop-statusbar').getBoundingClientRect().bottom,dock:document.querySelector('.window-stage').getBoundingClientRect().bottom}));
  check('Maximized Records preserves the small dock gap', expanded.x===0&&Math.abs(expanded.y-chromeBounds.bar)<1&&expanded.width===viewport.width&&Math.abs(expanded.y+expanded.height-(chromeBounds.dock-12))<1);
  check('Maximized app keeps the status bar visible and reveals dock on demand', await page.locator('.desktop-statusbar').isVisible() && await page.locator('.dock-region').evaluate(e => e.inert));
  await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(root, 'artifacts/records-fullscreen.png') });
  await page.mouse.move(viewport.width / 2, viewport.height - 2);
  await page.waitForFunction(() => !document.querySelector('.dock-region').inert);
  await page.waitForTimeout(250);
  const dock = await page.locator('.dock-pill').boundingBox();
  check('Bottom-center edge raises dock to its usual position', dock.y >= 0 && dock.y + dock.height <= viewport.height);
  await page.mouse.move(viewport.width / 2, viewport.height - 70);
  check('Dock stays revealed while using it', await page.locator('.dock-region').evaluate(e => !e.inert));
  await page.mouse.move(viewport.width / 2, viewport.height / 2);
  await page.waitForFunction(() => document.querySelector('.dock-region').inert);
  await page.mouse.move(viewport.width / 2, viewport.height - 2);
  await page.waitForFunction(() => !document.querySelector('.dock-region').inert);
  await page.getByRole('button', { name: 'Shut down Electron OS', exact: true }).hover();
  check('Direct environment controls stay usable in the revealed fullscreen dock', await page.getByRole('button', { name: 'Minimize Electron OS', exact: true }).isEnabled() && await page.locator('.dock-region').evaluate(e => !e.inert));
  await page.mouse.move(viewport.width / 2, viewport.height / 2);
  await page.waitForFunction(() => document.querySelector('.dock-region').inert);
  check('Dock hides again after leaving its direct controls', await page.locator('.dock-region').evaluate(e => e.inert));
  await page.getByRole('button', { name: 'Restore Records size', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('main').classList.contains('is-immersive'));
  check('Restoring app size returns the desktop dock and status bar', await page.locator('.dock-region').evaluate(e => !e.inert) && await page.locator('.desktop-statusbar').isVisible());
  await page.getByRole('button', { name: 'Close Records', exact: true }).click(); await phase('closed');
  await page.getByRole('button', { name: 'Records', exact: true }).click(); await phase('visible');
  check('Session data survives closing and reopening Records', await table.locator('tbody tr').count() === 7);
  check('No renderer errors', errors.length === 0);
  await fs.writeFile(path.join(root, 'artifacts/records-verification.json'), JSON.stringify({ checks, errors }, null, 2) + '\n');
} finally { await app.close(); }
